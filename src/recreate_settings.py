import os

def create_file(filepath, content):
    """Create a file with UTF-8 encoding."""
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    
    print(f"Created {filepath}")

def main():
    """Main function to recreate settings files."""
    settings_dir = os.path.join('core', 'settings')
    
    # Create settings directory if it doesn't exist
    os.makedirs(settings_dir, exist_ok=True)
    
    # Create files
    create_file(os.path.join(settings_dir, '__init__.py'), init_content)
    create_file(os.path.join(settings_dir, 'base.py'), base_content)
    create_file(os.path.join(settings_dir, 'development.py'), development_content)
    create_file(os.path.join(settings_dir, 'production.py'), production_content)

if __name__ == "__main__":
    main() 